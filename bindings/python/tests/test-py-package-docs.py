"""The documentation of the package (help(opengeode_io)) stays correct: the
examples are executed as doctests, every module and bound function has a
docstring and named arguments, and the generated __init__.py of the wheel
carries the same text.

Arguments: the text file of the documentation, the wheel package directory
generated by CMake. This script must not import opengeode_io before the
examples: they show the effect of the import."""

import ast
import doctest
import inspect
import io
import os
import sys

import geode_test_env

import opengeode


def check(condition, message):
    if not condition:
        raise ValueError("[Test] " + message)


def run_examples(documentation):
    parser = doctest.DocTestParser()
    test = parser.get_doctest(documentation, {}, "opengeode_io", None, 0)
    check(len(test.examples) >= 5, f"Only {len(test.examples)} examples")
    output = io.StringIO()
    runner = doctest.DocTestRunner(verbose=False, optionflags=doctest.ELLIPSIS)
    runner.run(test, out=output.write)
    results = runner.summarize(verbose=False)
    check(results.failed == 0, f"{results.failed} example(s) failed:\n{output.getvalue()}")


def check_docstrings(documentation):
    import opengeode_io
    import opengeode_io_py_image
    import opengeode_io_py_mesh
    import opengeode_io_py_model
    import opengeode_io_py_time_series
    import image_io
    import mesh_io
    import model_io
    import time_series_io

    check(opengeode_io.__doc__ == documentation, "Wrong opengeode_io.__doc__")
    for module in [
        image_io, mesh_io, model_io, time_series_io,
        opengeode_io_py_image, opengeode_io_py_mesh,
        opengeode_io_py_model, opengeode_io_py_time_series,
    ]:
        check(module.__doc__ and len(module.__doc__) > 40, f"No docstring in {module.__name__}")
    for module, name in [
        (opengeode_io_py_image, "OpenGeodeIOImageLibrary"),
        (opengeode_io_py_mesh, "OpenGeodeIOMeshLibrary"),
        (opengeode_io_py_model, "OpenGeodeIOModelLibrary"),
        (opengeode_io_py_time_series, "OpenGeodeIOTimeSeriesLibrary"),
    ]:
        library = getattr(module, name)
        check(library.__doc__, f"No docstring for {name}")
        check(library.initialize.__doc__, f"No docstring for {name}.initialize")
        check(
            isinstance(inspect.getattr_static(library, "initialize"), staticmethod),
            f"{name}.initialize should be static",
        )
        check(
            "Initialize self" not in (library.__init__.__doc__ or ""),
            f"{name} should document its missing constructor",
        )
        try:
            library()
        except TypeError:
            pass
        else:
            raise ValueError(f"[Test] {name} should not be constructible")
        # No instance is needed: initialize is called on the class, twice
        library.initialize()
        library.initialize()


def check_wheel_init(documentation, wheel_directory):
    init = os.path.join(wheel_directory, "__init__.py")
    with open(init, encoding="utf-8") as file:
        content = file.read()
    check(
        ast.get_docstring(ast.parse(content), clean=False) == documentation,
        "Wrong __init__.py docstring",
    )
    for name in ["image_io", "mesh_io", "model_io", "time_series_io"]:
        path = os.path.join(wheel_directory, name + ".py")
        with open(path, encoding="utf-8") as file:
            module = ast.parse(file.read())
        check(ast.get_docstring(module), f"No docstring in the wheel {name}.py")


if __name__ == "__main__":
    with open(sys.argv[1], encoding="utf-8") as file:
        documentation = file.read()
    run_examples(documentation)
    check_docstrings(documentation)
    check_wheel_init(documentation, sys.argv[2])
